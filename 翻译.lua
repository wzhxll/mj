local FlatTranslation = {}
local function __flatten(tbl)
    if type(tbl) ~= "table" then return end
    for k, v in pairs(tbl) do
        if type(v) == "table" then
            if type(k) == "string" and k ~= ""
               and type(v.Name) == "string" and v.Name ~= "" then
                FlatTranslation[k] = v.Name
                if type(v.Description) == "string" and v.Description ~= "" then
                    FlatTranslation[k .. ".Description"] = v.Description
                end
            else
                __flatten(v)
            end
        elseif type(k) == "string" and type(v) == "string" and k ~= "" then
            FlatTranslation[k] = v
        end
    end
end
__flatten(TranslationData)

TranslationData.Flat = FlatTranslation

return TranslationData